import { test, expect } from "@playwright/test";

test("profile address persists, prefills checkout, and stays separate between accounts", async ({ page }) => {
  await page.clock.setFixedTime(new Date("2026-10-15T04:00:00Z"));
  await page.setViewportSize({ width: 320, height: 844 });
  await page.goto("/account");
  await page.locator(".identity-card").filter({ hasText: "Aina" }).click();
  await page.getByRole("button", { name: /^Account:/ }).click();
  await page.locator(".account-dropdown").getByRole("link", { name: "My profile" }).click();
  await expect(page).toHaveURL(/\/profile$/);
  await page.getByLabel("Contact number").fill("0123456789");
  await page.getByLabel("Recipient name").fill("Test Reader");
  await page.getByLabel("Address line 1", { exact: true }).fill("123 Test Street");
  await page.getByLabel("Postcode", { exact: true }).fill("50000");
  await page.getByLabel("City", { exact: true }).fill("Kuala Lumpur");
  await page.getByLabel("State / province").selectOption("Kuala Lumpur");
  await page.getByRole("button", { name: "Save address", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("Delivery details saved");
  await page.reload();
  await expect(page.getByLabel("Address line 1", { exact: true })).toHaveValue("123 Test Street");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBeTruthy();
  await page.goto("/books/00000000-0000-4000-8000-000000000009");
  await page.getByRole("button", { name: "Reserve a copy" }).click();
  await page.goto("/cart");
  await page.getByRole("button", { name: "Join preorder queue" }).click();
  await expect(page.getByLabel("Address line 1", { exact: true })).toHaveValue("123 Test Street");
  await page.goto("/account");
  await page.locator(".identity-card").filter({ hasText: "Daniel" }).click();
  await page.goto("/profile");
  await expect(page.getByLabel("Address line 1", { exact: true })).toHaveValue("");
  await page.getByRole("button", { name: /^Account:/ }).click();
  await page.locator(".account-dropdown").getByRole("button", { name: "Log out", exact: true }).click();
  await expect(page.getByRole("dialog")).toBeVisible();
  await page.getByRole("button", { name: "Stay signed in" }).click();
  await expect(page.getByRole("button", { name: /^Account:/ })).toBeVisible();
  await page.locator(".account-dropdown").getByRole("button", { name: "Log out", exact: true }).click();
  await page.getByRole("button", { name: "Confirm logout" }).click();
  await expect(page.locator("header").getByRole("link", { name: "Sign in", exact: true })).toBeVisible();
  await page.goto("/profile");
  await expect(page.getByLabel("Account email")).toHaveCount(0);
});
